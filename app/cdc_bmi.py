@dataclass(slots=True)
class TeenBMIStatus:
    bmi: float
    age_months: int
    p85: float
    p95: float
    severe_cutoff: float
    category: str


def age_in_completed_months(birth_date: date, on_date: date | None = None) -> int:
    on_date = on_date or date.today()
    months = (on_date.year - birth_date.year) * 12 + on_date.month - birth_date.month
    if on_date.day < birth_date.day:
        months -= 1
    return months


def teen_bmi_status(
    sex: str,
    birth_date: date | None,
    height_cm: float,
    weight_kg: float,
    fallback_age_years: int | None = None,
    on_date: date | None = None,
) -> TeenBMIStatus | None:
    if height_cm <= 0 or weight_kg <= 0:
        return None

    if birth_date is not None:
        age_months = age_in_completed_months(birth_date, on_date)
    elif fallback_age_years is not None:
        # Existing records may not have DOB yet. Mid-year is a conservative
        # temporary approximation until the user re-enters their birth date.
        age_months = int(fallback_age_years * 12 + 6)
    else:
        return None

    table = CDC_BMI.get(sex)
    if not table:
        return None
    age_months = max(min(age_months, max(table)), min(table))
    p85, p95, severe_cutoff = table[age_months]

    height_m = height_cm / 100.0
    bmi = weight_kg / (height_m * height_m)
    if bmi >= severe_cutoff or bmi >= 35.0:
        category = "severe_obesity"
    elif bmi >= p95:
        category = "obesity"
    elif bmi >= p85:
        category = "overweight"
    else:
        category = "below_overweight"

    return TeenBMIStatus(
        bmi=bmi,
        age_months=age_months,
        p85=p85,
        p95=p95,
        severe_cutoff=severe_cutoff,
        category=category,
    )
